#!/usr/bin/env python3
"""Pull the icon art out of the design canvas into art/art.js (one file shared by the POS, the phones and the website).

    python3 tools/art/extract_icons.py <folder with Ingredients.dc.html and Icons.dc.html> art/art.js

The canvas is the source of truth: draw or change an icon there, run this, commit art/art.js.
Each icon keeps its own viewBox and colours. Menu icons keep the tile colour the canvas gave them.
"""
import re, sys, json, html, os

src, out = sys.argv[1], sys.argv[2]

def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', html.unescape(s).lower()).strip('-')

def clean(svg):
    # only the inner drawing is kept: never strip width/height here, shapes inside the icon need them
    return svg.strip()

def balanced_svg(text, start):
    """text[start:] begins with '<svg'. Return (inner, viewBox, end) honouring nested <svg> elements."""
    m = re.match(r'<svg\b([^>]*)>', text[start:])
    attrs = m.group(1)
    vb = re.search(r'viewBox="([^"]+)"', attrs).group(1)
    pos = start + m.end()
    depth = 1
    inner_start = pos
    while depth:
        o = text.find('<svg', pos)
        c = text.find('</svg>', pos)
        if c < 0:
            raise ValueError('unbalanced svg')
        if 0 <= o < c:
            depth += 1
            pos = o + 4
        else:
            depth -= 1
            pos = c + 6
            if depth == 0:
                return text[inner_start:c], vb, pos
    raise ValueError('unbalanced svg')

def label_after(text, pos):
    m = re.match(r'\s*</span>\s*<span[^>]*>(.*?)</span>', text[pos:], flags=re.S)
    return html.unescape(m.group(1)).strip() if m else None

ing = {}
s = open(os.path.join(src, 'Ingredients.dc.html')).read()
for m in re.finditer(r'<span class="b"><svg', s):
    inner, vb, end = balanced_svg(s, m.end() - 4)
    label = label_after(s, end)
    if label:
        ing[slug(label)] = {'vb': vb, 'svg': clean(inner), 'name': label}

menu = {}
s = open(os.path.join(src, 'Icons.dc.html')).read()
for m in re.finditer(r'<span style="[^"]*?background:\s*(#[0-9A-Fa-f]{3,8})[^"]*">\s*<svg', s):
    inner, vb, end = balanced_svg(s, m.end() - 4)
    label = label_after(s, end)
    if label:
        menu[slug(label)] = {'vb': vb, 'svg': clean(inner), 'bg': m.group(1), 'name': label}

js = ("/* Josie's art kit. GENERATED by tools/art/extract_icons.py from the design canvas. Do not edit by hand. */\n"
      "(function (w) {\n  'use strict';\n  var ART = w.J2ART = " + json.dumps({'ing': ing, 'menu': menu}, ensure_ascii=False, separators=(',', ':')) + ";\n"
      """  /* art.svg('ing', 'bacon', 44) -> an inline <svg> string. kind: 'ing' | 'menu'. */
  ART.svg = function (kind, key, size, cls) {
    var e = ART[kind] && ART[kind][key];
    if (!e) { return ''; }
    return '<svg class="' + (cls || 'art') + '" viewBox="' + e.vb + '" width="' + (size || 48) + '" height="' + (size || 48) + '" aria-hidden="true">' + e.svg + '</svg>';
  };
  ART.has = function (kind, key) { return !!(ART[kind] && ART[kind][key]); };
}(window));
""")
open(out, 'w').write(js)
print('ingredients:', len(ing), 'menu/map icons:', len(menu), 'bytes:', len(js))
print('ing keys:', ', '.join(sorted(ing)))
print('menu keys:', ', '.join(sorted(menu)))
